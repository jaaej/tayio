-- 0058_tutor_profile_photos.sql
-- Tutor profile photos are kept in a dedicated private bucket. Application
-- role checks precede service-signed uploads and reads, so no authenticated
-- client storage policy is required.

begin;

insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'profile-photos',
  'profile-photos',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update
set
  public = false,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

commit;
